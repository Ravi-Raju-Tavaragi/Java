package Fri04SEP;

import java.util.Scanner;

public class SumofN
{
    public static void main(String[]args)
    {
        Scanner sc = new Scanner(System.in);
        System.out.println("Enter Range to Sum");
        int n = sc.nextInt();

        for(n = 1; n <= n; )
        {
            System.out.println(n);
        }
        sc.close();
    }
    
}
