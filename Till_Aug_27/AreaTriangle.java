public class AreaTriangle
{
    public static void main(String[]args)
    {
        double base = 12;
        double hight = 11.12;
        double area_of_triangle;
        System.out.println("Base of Triangle is :" + base);
         System.out.println("Hight of Triangle is :" + hight);

        area_of_triangle = ((0.5)*(base * hight));
        System.out.println("Area of Triangle is :" + area_of_triangle);
    }
}
